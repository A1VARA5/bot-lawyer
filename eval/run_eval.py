"""Ask every eval question in the dataset through the local Bot Lawyer API and save the transcript for human marking.
Usage: python run_eval.py [--base http://localhost:3111] [--limit N]
Reads questions with the Sanity CLI (logged in). Writes results.json and results.md next to this file."""
import json, subprocess, sys, time, urllib.request, os
base = "http://localhost:3111"
limit = None
args = sys.argv[1:]
if "--base" in args: base = args[args.index("--base")+1]
if "--limit" in args: limit = int(args[args.index("--limit")+1])
studio = os.path.join(os.path.dirname(__file__), "..", "studio")
q = '*[_type=="question"] | order(_id){_id, text, kind, expectedAnswer, situation, "expectedRules": expectedRules[]->{_id, title}, note}'
out = subprocess.run(["npx", "sanity", "documents", "query", q, "--dataset", "production", "--api-version", "2025-08-15"], cwd=studio, capture_output=True, text=True, shell=True, encoding="utf-8", errors="ignore")
raw = out.stdout[out.stdout.index("["):]
questions = json.loads(raw)
if limit: questions = questions[:limit]
print(f"{len(questions)} questions")
results = []
for i, item in enumerate(questions, 1):
    sit = item.get("situation") or {}
    facts = ", ".join(f"{k}: {v}" for k, v in sit.items() if v not in (None, "", []))
    text_in = item["text"] + (f" (My situation: {facts}.)" if facts else "")
    body = {"messages": [{"id": "u1", "role": "user", "parts": [{"type": "text", "text": text_in}]}]}
    req = urllib.request.Request(base + "/api/lawyer", data=json.dumps(body).encode(), headers={"Content-Type": "application/json"})
    t0 = time.time()
    resp = None
    for attempt in range(3):
        try:
            resp = urllib.request.urlopen(req, timeout=240).read().decode("utf-8", "ignore")
            if '"type": "error"' in resp or '"type":"error"' in resp:
                raise RuntimeError("stream error event")
            break
        except Exception as e:
            resp = "data: " + json.dumps({"type": "error", "errorText": str(e)})
            if attempt < 2:
                print(f"   retry {attempt + 1} after error: {str(e)[:80]}")
                time.sleep(61)
    time.sleep(11)  # stay under the app's 6 per minute limiter
    dt = time.time() - t0
    text, tools, err = [], [], None
    for line in resp.splitlines():
        if not line.startswith("data:"): continue
        try: ev = json.loads(line[5:].strip())
        except Exception: continue
        t = ev.get("type", "")
        if t == "text-delta": text.append(ev.get("delta", ""))
        elif t == "tool-input-available": tools.append({"tool": ev.get("toolName"), "input": ev.get("input")})
        elif t == "error": err = ev.get("errorText")
    answer = "".join(text)
    results.append({**item, "answer": answer, "tools": tools, "seconds": round(dt, 1), "error": err})
    print(f"[{i}/{len(questions)}] {item['_id']} {item['kind']} {dt:.1f}s tools={[t['tool'] for t in tools]}")
    with open("results.json", "w", encoding="utf-8") as f: json.dump(results, f, indent=1, ensure_ascii=False)
with open("results.md", "w", encoding="utf-8") as f:
    f.write("# Bot Lawyer eval run\n\nMark each PASS / FAIL in the Verdict line. Generated by run_eval.py.\n\n")
    for r in results:
        f.write(f"## {r['_id']} ({r['kind']}) {r['seconds']}s\n\n**Q:** {r['text']}\n\n**Situation:** {json.dumps(r.get('situation'))}\n\n**Expected:** {r['expectedAnswer']}\n\n**Expected rules:** {', '.join(x['_id'] for x in (r.get('expectedRules') or []))}\n\n")
        if r.get("note"): f.write(f"**Note:** {r['note']}\n\n")
        f.write("**Tools:** " + "; ".join(f"{t['tool']}: {json.dumps(t['input'])[:160]}" for t in r["tools"]) + "\n\n")
        f.write("**Answer:**\n\n" + (r["answer"] or f"(no answer, error: {r['error']})") + "\n\n**Verdict:** \n\n---\n\n")
print("wrote results.json and results.md")
